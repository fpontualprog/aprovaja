-- Schema inicial do banco de questões do APROVAJÁ.
create table if not exists public.questoes (
    id bigint generated by default as identity primary key,
    evento_url text not null,
    numero integer not null,
    enunciado text not null,
    texto_apoio text null,
    tipo text not null default 'certo_errado',
    gabarito text null,
    disciplina text null,
    tem_imagem boolean not null default false,
    imagens text null,
    created_at timestamp with time zone not null default now(),
    constraint questoes_evento_url_numero_key unique (evento_url, numero)
);

-- Opcional: valida os valores mais comuns do gabarito sem impedir NULL.
alter table public.questoes
    drop constraint if exists questoes_gabarito_check;
alter table public.questoes
    add constraint questoes_gabarito_check
    check (gabarito is null or upper(gabarito) in ('C', 'E', 'X'));
